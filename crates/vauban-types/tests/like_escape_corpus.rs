/// Every form of [`CORPUS`] matches exactly the values its row lists, out of the 26 values.
#[test]
fn escape_in_a_class_corpus() {
    let latin1 = Collation::DEFAULT;
    let mut checked = 0usize;
    for (pattern, escape, filler, matched) in CORPUS {
        for template in VALUE_TEMPLATES {
            let value = template.replace('E', &filler.to_string());
            let expected = matched.contains(&value.as_str());
            assert_eq!(
                latin1.like(&value, pattern, *escape),
                expected,
                "{value:?} LIKE {pattern:?} ESCAPE {escape:?}"
            );
            checked += 1;
        }
    }
    assert_eq!(checked, 466 * 26);
}

/// The escape character is recognised by identity, not through the collation: under
/// `_CI_AS`, `ESCAPE 'x'` leaves an `X` of the pattern an ordinary character.
#[test]
fn escape_is_recognised_by_identity_corpus() {
    let latin1 = Collation::DEFAULT;
    for (pattern, escape, matched) in CORPUS_CI {
        for value in VALUES_CI {
            assert_eq!(
                latin1.like(value, pattern, Some(*escape)),
                matched.contains(&value),
                "{value:?} LIKE {pattern:?} ESCAPE {escape:?}"
            );
        }
    }
}
