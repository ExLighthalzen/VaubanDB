//! The escape character in and around a `[...]` class of `LIKE`.
//!
//! Every line of the two tables below is one `SELECT CASE WHEN v LIKE p ESCAPE e THEN 1
//! WHEN NOT (...) THEN 0 ELSE -1 END`, one column per value. The tables hold the values
//! the pattern **matches**; every other value of the same row is `0` (no row is `-1` or
//! an error).
//!
//! Axes of [`CORPUS`] (466 forms): the position of the escape (before `[`, inside the
//! class before an ordinary character, before `]`, before `^`, before `-`, on a range
//! bound, at the end of the pattern, inside an unclosed class) times the escape
//! character (`\`, `!`, `[`, `]`, `%`, `_`, `^`, `-`), plus the degenerate classes
//! `[]`, `[^]`, `[a-]`, `[-a]`, `[a`, `[^`, `[]]`, `[^]]`, `[[]`, `[-]`, and the same
//! patterns without any `ESCAPE` clause as a control (`None`).
//!
//! Axes of [`CORPUS_CI`] (28 forms): the case of the escape character in the pattern
//! under the default `_CI_AS` collation, which settles that the escape is recognised by
//! identity and not through the collation. The table holds the `_CI_AS` answers alone:
//! under `Latin1_General_CS_AS` and `Latin1_General_BIN2` the escape is read the same
//! way, but the case sensitivity of those collations, which this crate does not
//! implement yet (a gap of `compare`, not of `LIKE`), and the code point order of a
//! `_BIN2` range change what a pattern matches.
//!
//! Not crossed, on purpose: the order of a range under `_CS_AS`/`_BIN2` (same gap, and
//! the `[bX-d]` form above is the one place it shows), supplementary characters (out of
//! V1), `NOT LIKE` (a pure negation) and `PATINDEX` (no `ESCAPE` clause). The Windows
//! collations (`Latin1_General_CI_AS`, `_CS_AS`, `_100_CI_AS`) differ on one rule that is
//! not the escape: an unclosed `[` is closed by the end of the pattern there, where the
//! SQL and binary collations match nothing; documented on `Collation::like`.

